// Generates src/ui/tokens.css from src/ui/tokens.json. `--check` fails if the CSS is stale.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../src/ui/', import.meta.url);
const t = JSON.parse(readFileSync(new URL('tokens.json', dir), 'utf8'));

const vars = (prefix, obj) => Object.entries(obj).map(([k, v]) => `  --${prefix}-${k}: ${v};`).join('\n');
const scale = [
  `  --font-family: ${t.font.family};`, `  --font-mono: ${t.font.mono};`,
  vars('font-size', t.font.size), vars('line-height', t.font.lineHeight), vars('font-weight', t.font.weight),
  `  --measure: ${t.font.measure};`, vars('space', t.space), vars('radius', t.radius), vars('target', t.target),
  `  --focus-width: ${t.focus.width};`, `  --focus-offset: ${t.focus.offset};`,
  `  --motion-micro: ${t.motion.micro};`, `  --motion-panel: ${t.motion.panel};`, `  --motion-easing: ${t.motion.easing};`,
].join('\n');

const css = `/* GENERATED by scripts/build-tokens.mjs from tokens.json — do not edit. */
:root {
${scale}
${vars('color', t.color.light)}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars('color', t.color.dark).replace(/^ {2}/gm, '    ')}
    color-scheme: dark;
  }
}
:root[data-theme='dark'] {
${vars('color', t.color.dark)}
  color-scheme: dark;
}
@media (prefers-reduced-motion: reduce) {
  :root { --motion-micro: 0ms; --motion-panel: 0ms; }
}
`;
const target = new URL('tokens.css', dir);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== css) { console.error('tokens.css is stale: run `npm run tokens`'); process.exit(1); }
  console.log('tokens.css is up to date');
} else {
  writeFileSync(target, css);
  console.log('wrote src/ui/tokens.css');
}
